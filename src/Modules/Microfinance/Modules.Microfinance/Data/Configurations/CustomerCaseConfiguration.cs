using FSH.Modules.Microfinance.Domain;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace FSH.Modules.Microfinance.Data.Configurations;

public class CustomerCaseConfiguration : IEntityTypeConfiguration<CustomerCase>
{
    public void Configure(EntityTypeBuilder<CustomerCase> builder)
    {
        builder.ToTable("CustomerCases", "microfinance");
        builder.HasKey(x => x.Id);
        builder.Property(x => x.Name).IsRequired().HasMaxLength(256);
        builder.HasIndex(x => x.TenantId);
    }
}
